"""Generate the sentence types the first neutral detector never saw, then have the LLM check each one. CUDA GPU.

The first neutral set (gen_neutral.py) only had people doing everyday things, so the detector learned
"general claim = stereotype-related" and flagged "Water is healthy." and "Men like apples." This script adds:

  kind          gender?  label        example
  nogender_*    no       not-gender   Water is healthy. / Dogs are loyal. / I like pizza. / Asians are good at math.
  gen_neutral   yes      neutral      Men like apples.   (same form as a stereotype, ordinary content)
  gen_fact      yes      neutral      My sister lives in Boston.
  gen_stereo    yes      stereotype   Men like beer.      + its gender swap "Women like beer." as anti-stereotype

Stereotype claims are generated by the same model as the neutral ones, so writing style can't separate the classes.
Each generated sentence is then checked by the model (a separate prompt); only sentences whose check agrees with the
intended kind are kept. The old neutral set (neutral_generated.csv) is checked the same way and cleaned.

Writes data/external/neutral_v2.csv: sentence, kind, gender (1/0), label3 (0 anti, 1 stereo, 2 neutral), group
and data/external/neutral_generated_clean.csv (old set minus sentences the check calls stereotype-related, B).

  python experiments/gen_neutral_v2.py [Qwen/Qwen2.5-14B-Instruct]
"""
import random, re, sys
from pathlib import Path
import pandas as pd, torch
from transformers import AutoModelForCausalLM, AutoTokenizer

ROOT = Path(__file__).resolve().parent.parent
MODEL = next((a for a in sys.argv[1:] if not a.startswith("--")), "Qwen/Qwen2.5-14B-Instruct")
PER_CALL = 10

TOPICS = ["food and cooking", "weather and seasons", "science and nature", "household objects", "cities and travel",
          "sports and exercise", "music and art", "technology and computers", "school and studying", "money and shopping",
          "health and medicine", "transportation", "plants and gardening", "history", "work and offices", "holidays",
          "hobbies", "movies and books", "the ocean", "space and astronomy", "cars", "clothing", "time and schedules",
          "animals on a farm", "pets", "wild animals", "drinks", "the human body", "buildings", "games"]

KINDS = {  # kind: (prompt, calls, gender, label3)
    "nogender_fact": ("""Write {n} different short sentences about {topic}. Each states an ordinary fact, opinion or
general claim about things, places or ideas. No people at all: no pronouns like he/she/I/you/they, no words for
people or groups of people.""", 60, 0, 2),
    "nogender_animal": ("""Write {n} different short sentences making general claims or stating facts about animals
(related to {topic} if possible), for example "Dogs are loyal." Do not mention any people or gender words.""", 25, 0, 2),
    "nogender_person": ("""Write {n} different short everyday sentences about {topic} written in the first or second
person ("I ...", "We ...", "You ...") or about "people" in general. Never reveal anyone's gender: no he/she, no
gendered words like man, woman, mother, brother, and no names.""", 35, 0, 2),
    "nogender_group": ("""Write {n} different short sentences making ordinary, non-stereotypical general claims about a
group of people defined by job, age, school, hobby or place (for example "Students are busy during finals.",
"Doctors work long hours."), related to {topic} if possible. No gender words, no he/she, no names.""", 35, 0, 2),
    "nogender_stereo": ("""For a research dataset that trains a detector to tell gender stereotypes apart from other
kinds of stereotype, write {n} different short sentences that each state a common stereotype about a group defined
by race, ethnicity, nationality, religion, age, region or social class (not gender). Do not use any gender words
or he/she.""", 25, 0, 2),
    "gen_neutral": ("""Write {n} different short sentences that make a general claim about men or about women (or
boys, girls, mothers, fathers, ...) where the claim is ordinary and NOT a gender stereotype: something just as true
of the other gender, for example "Men like apples.", "Women own bicycles.", "Fathers drink water." Related to
{topic} if possible. Avoid anything that is commonly associated with one gender.""", 45, 1, 2),
    "gen_fact": ("""Write {n} different short sentences about one specific person, using a gender word (she, he, my
sister, his uncle, the woman, ...), stating a plain fact or event related to {topic}, for example "My sister lives in
Boston." The sentence must not say or imply anything about what a gender is like or supposed to do.""", 30, 1, 2),
    "gen_stereo": ("""For a research dataset that trains a gender-stereotype detector, write {n} different short
sentences that each state a common gender stereotype as a general claim about men or about women (or boys, girls,
mothers, fathers, ...), related to {topic} if possible, for example "Men like beer.", "Women like shopping." Use
simple wording.""", 30, 1, 1),
}

CHECK = """Classify this sentence. Answer with exactly one letter.
A: it does not refer to any gender at all (no gendered words or pronouns about people)
B: it refers to a gender and states, implies or plays on a gender stereotype (what men or women are like, good at,
   interested in, or supposed to do)
C: it refers to a gender, but says nothing stereotypical about gender (an ordinary fact or claim equally true of
   any gender)
D: it is a stereotype about a group defined by something other than gender (race, age, religion, nationality, ...)

Sentence: {s}
Answer:"""
EXPECT = {"nogender_fact": "A", "nogender_animal": "A", "nogender_person": "A", "nogender_group": "A",
          "nogender_stereo": "D", "gen_neutral": "C", "gen_fact": "C", "gen_stereo": "B"}

SWAP = {"he": "she", "she": "he", "him": "her", "his": "her", "her": "his", "himself": "herself", "herself": "himself",
        "man": "woman", "woman": "man", "men": "women", "women": "men", "boy": "girl", "girl": "boy", "boys": "girls",
        "girls": "boys", "father": "mother", "mother": "father", "fathers": "mothers", "mothers": "fathers",
        "dad": "mom", "mom": "dad", "dads": "moms", "moms": "dads", "son": "daughter", "daughter": "son",
        "sons": "daughters", "daughters": "sons", "brother": "sister", "sister": "brother", "brothers": "sisters",
        "sisters": "brothers", "husband": "wife", "wife": "husband", "husbands": "wives", "wives": "husbands",
        "male": "female", "female": "male", "males": "females", "females": "males", "gentleman": "lady",
        "lady": "gentleman", "gentlemen": "ladies", "ladies": "gentlemen", "guys": "gals", "uncle": "aunt",
        "aunt": "uncle", "grandfather": "grandmother", "grandmother": "grandfather", "king": "queen", "queen": "king",
        "boyfriend": "girlfriend", "girlfriend": "boyfriend", "masculine": "feminine", "feminine": "masculine"}
GENDER = re.compile(r"\b(" + "|".join(SWAP) + r")\b", re.I)


def swap(s):
    def f(m):
        w = m.group(0); r = SWAP[w.lower()]
        return r.capitalize() if w[0].isupper() else r
    return GENDER.sub(f, s)


def chat(tok, model, prompts, max_new, temp):
    out = []
    for i in range(0, len(prompts), 16):
        texts = [tok.apply_chat_template([{"role": "user", "content": p}], add_generation_prompt=True, tokenize=False)
                 for p in prompts[i:i + 16]]
        enc = tok(texts, return_tensors="pt", padding=True).to("cuda")
        kw = dict(do_sample=True, temperature=temp, top_p=0.95) if temp else dict(do_sample=False)
        gen = model.generate(**enc, max_new_tokens=max_new, pad_token_id=tok.eos_token_id, **kw)
        out += [tok.decode(o, skip_special_tokens=True).strip() for o in gen[:, enc["input_ids"].shape[1]:]]
        print(f"  {min(i + 16, len(prompts))}/{len(prompts)}", flush=True)
    return out


def parse_list(text):
    lines = [re.sub(r"^\s*(\d+[.)]|[-*•])\s*", "", l).strip().strip('"') for l in text.split("\n")]
    return [l for l in lines if 3 <= len(l.split()) <= 25 and l[-1:] in ".!?" and not l.lower().startswith("here")]


@torch.no_grad()
def main():
    random.seed(0); torch.manual_seed(0)
    tok = AutoTokenizer.from_pretrained(MODEL, padding_side="left")
    model = AutoModelForCausalLM.from_pretrained(MODEL, dtype=torch.float16, device_map={"": 0}).eval()

    rows = []
    for kind, (prompt, calls, gender, label3) in KINDS.items():
        print(kind, flush=True)
        prompts = [prompt.format(n=PER_CALL, topic=random.choice(TOPICS)).replace("\n", " ") +
                   " Answer with a numbered list only." for _ in range(calls)]
        for text in chat(tok, model, prompts, 400, 0.9):
            rows += [{"sentence": s, "kind": kind, "gender": gender, "label3": label3} for s in parse_list(text)]
    df = pd.DataFrame(rows)
    df = df[~df["sentence"].str.lower().duplicated()]
    has_g = df["sentence"].str.contains(GENDER)
    df = df[(df["gender"] == 1) == has_g]  # gender kinds must contain a gender word; the others must not
    print("generated (deduplicated, gender-word check):", df["kind"].value_counts().to_dict(), flush=True)

    print("checking", flush=True)
    ans = chat(tok, model, [CHECK.format(s=s) for s in df["sentence"]], 2, 0)
    df["check"] = [a[:1].upper() for a in ans]
    df = df[df["check"] == df["kind"].map(EXPECT)].copy()
    print("kept after check:", df["kind"].value_counts().to_dict(), flush=True)

    df["group"] = [f"v2_{i}" for i in range(len(df))]
    st = df[df["kind"] == "gen_stereo"]  # each stereotype claim gets its gender swap as an anti-stereotype partner
    anti = st.assign(sentence=st["sentence"].map(swap), kind="gen_anti", label3=0)
    anti = anti[anti["sentence"] != st["sentence"]]
    df = pd.concat([df[df["kind"] != "gen_stereo"], st[st["group"].isin(anti["group"])], anti])
    df[["sentence", "kind", "gender", "label3", "group"]].to_csv(ROOT / "data" / "external" / "neutral_v2.csv", index=False)
    print("wrote neutral_v2.csv:", df["kind"].value_counts().to_dict(), flush=True)

    old = pd.read_csv(ROOT / "data" / "external" / "neutral_generated.csv")
    ans = chat(tok, model, [CHECK.format(s=s) for s in old["sentence"]], 2, 0)
    old["check"] = [a[:1].upper() for a in ans]
    print(f"old neutral set: {len(old)}, check says {old['check'].value_counts().to_dict()}", flush=True)
    # Drop only B (stereotype-related). On these all-gendered sentences the check uses A ("no gender") for plain
    # actions like "He went to the store.", which are exactly the neutral sentences we want, so A and C are kept.
    old[old["check"] != "B"][["pair_id", "sentence"]].to_csv(
        ROOT / "data" / "external" / "neutral_generated_clean.csv", index=False)
    old[old["check"] == "B"].to_csv(ROOT / "data" / "external" / "neutral_generated_dropped.csv", index=False)
    print("wrote neutral_generated_clean.csv", flush=True)


if __name__ == "__main__":
    main()
